/**
 * `notifications` table: one row per send request, with its delivery result.
 * The table itself is created by the migrations in src/database/migrations.
 */

// TypeORM decorators that map the class to the table.
import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
// Channel enum (email, sms, push, webhook).
import { NotificationChannel } from '../enums/notification-channel.enum.js';
// Status enum (pending, sent, failed).
import { NotificationStatus } from '../enums/notification-status.enum.js';

@Entity('notifications')
// Most lookups are "this tenant's notifications, newest first".
@Index('idx_notifications_tenant_created', ['tenantId', 'createdAt'])
export class Notification {
  // UUID generated by Postgres.
  @PrimaryGeneratedColumn('uuid')
  id: string;

  // Tenant (white-label client) that owns this notification.
  @Column({ name: 'tenant_id', type: 'varchar', length: 100 })
  tenantId: string;

  // Stored as text (not a Postgres enum) so new channels need no migration.
  @Column({ type: 'varchar', length: 20 })
  channel: NotificationChannel;

  // Email address, phone number, device token or URL.
  @Column({ type: 'varchar', length: 500 })
  recipient: string;

  // Final (rendered) subject.
  @Column({ type: 'varchar', length: 255, nullable: true })
  subject: string | null;

  // Plain-text content, if sent.
  @Column({ type: 'text', nullable: true })
  body: string | null;

  // Template name from src/views, if one was used.
  @Column({ type: 'varchar', length: 100, nullable: true })
  template: string | null;

  // Values used to fill the template (lets you re-render the email later).
  @Column({ type: 'jsonb', nullable: true })
  data: Record<string, unknown> | null;

  // Delivery state: pending -> sent | failed.
  @Column({ type: 'varchar', length: 20, default: NotificationStatus.Pending })
  status: NotificationStatus;

  // Message id returned by the delivery provider, if sent.
  @Column({
    name: 'provider_message_id',
    type: 'varchar',
    length: 255,
    nullable: true,
  })
  providerMessageId: string | null;

  // Error message, if delivery failed.
  @Column({ type: 'text', nullable: true })
  error: string | null;

  // Set by Postgres on insert.
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  // Set by TypeORM on every save.
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt: Date;
}
